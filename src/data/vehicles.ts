import { images, type ImageAsset } from './images.ts' // explicit extension: also loaded by vite.config.ts

export type VehicleStatus = 'available' | 'reserved' | 'sold'

/** Mirrors the future Supabase `vehicles` table (+ `vehicle_images` for `images`). */
export type Vehicle = {
  /** URL slug — /cars/:id */
  id: string
  status: VehicleStatus
  year: number
  make: string
  model: string
  variant?: string
  /** Philippine pesos */
  price: number
  /** Kilometres */
  mileage?: number
  transmission?: string
  fuelType?: string
  bodyType?: string
  engine?: string
  driveType?: string
  color?: string
  images: ImageAsset[]
  description: string
  features: string[]
  financingAvailable?: boolean
  tradeInAvailable?: boolean
  /** ISO date — drives the "Newest" sort */
  listedAt?: string
  /** Demo data: shows a SAMPLE badge and is kept out of the sitemap and structured data. */
  sample?: boolean
}

